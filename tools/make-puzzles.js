/**
 * MKJ Chess — Puzzle generator (build-time only).
 * -----------------------------------------------------------------------------
 * Feeds candidate positions through the independent forced-mate oracle and
 * emits puzzle data whose key move is the verified solution. Because the
 * solution comes from the same rules engine that plays the game, every emitted
 * puzzle is guaranteed to be legal and to have a real forced mate.
 *
 * Usage: node tools/make-puzzles.js
 */
import { writeFileSync } from 'node:fs';
import { validateFen, createPosition } from '../src/chess-rules.js';
import { shortestForcedMate } from '../src/mate-search.js';

/**
 * Candidate positions. The oracle decides which ones are actually forced
 * mates; anything without one is skipped rather than shipped.
 */
const CANDIDATES = [
  { id: 'back-rank', fen: '6k1/5ppp/8/8/8/8/5PPP/R5K1 w - - 0 1', theme: 'Back-rank mate' },
  { id: 'scholar', fen: 'r1bqkb1r/pppp1ppp/2n2n2/4p2Q/2B1P3/8/PPPP1PPP/RNB1K1NR w KQkq - 0 1', theme: 'Scholar' },
  { id: 'rook-mate2', fen: '1k6/8/1K6/8/8/8/8/R7 w - - 0 1', theme: 'King and rook' },
  { id: 'rook-mate2b', fen: '2k5/8/2K5/8/8/8/8/R7 w - - 0 1', theme: 'King and rook' },
  { id: 'two-rooks', fen: '7k/8/8/8/8/8/8/RR4K1 w - - 0 1', theme: 'Two rooks' },
  { id: 'castle-mate', fen: '6k1/5ppp/8/8/8/8/5PPP/4R1K1 w - - 0 1', theme: 'Rook mate' },
  { id: 'pawn-push', fen: '6k1/5ppp/8/8/8/8/PP3PPP/2R2RK1 w - - 0 1', theme: 'Rook lift' },
  { id: 'rook-square', fen: '6k1/5ppp/8/8/8/8/5PPP/3R2K1 w - - 0 1', theme: 'Back-rank' },
  // g8 is defended by the rook on g1, so the king cannot simply capture the
  // promoting pawn.
  { id: 'promo-mate', fen: '7k/6P1/8/8/8/8/8/6RK w - - 0 1', theme: 'Promotion' },
  // A rook on a1 plus a supported king cuts off the king's retreat.
  { id: 'king-rook', fen: 'k7/8/8/8/8/8/1K6/R7 w - - 0 1', theme: 'King and rook' },
  { id: 'double-rook', fen: '6k1/5ppp/8/8/8/8/5PPP/RR4K1 w - - 0 1', theme: 'Two rooks' },
  { id: 'rook-mate3', fen: '6k1/5ppp/8/8/8/8/5PPP/2R2RK1 w - - 0 1', theme: 'Rook mate' },
];

/** Two moves is the practical ceiling for a puzzle: longer ones are hard to
 *  verify by eye and unforgiving to play. */
const MAX_PUZZLE_MOVES = 2;

const puzzles = [];
const rejected = [];

for (const c of CANDIDATES) {
  const check = validateFen(c.fen);
  if (!check.ok) {
    rejected.push({ id: c.id, reason: `invalid FEN — ${check.error}` });
    continue;
  }

  const found = shortestForcedMate(createPosition(c.fen), MAX_PUZZLE_MOVES);
  if (!found) {
    rejected.push({ id: c.id, reason: 'no forced mate within 2 moves' });
    continue;
  }

  puzzles.push({
    id: c.id,
    theme: c.theme,
    fen: c.fen,
    moves: found.moves,
    keyMoves: found.keyMoves,
    difficulty: found.moves <= 1 ? 'easy' : 'medium',
  });
}

/**
 * Keep a varied set: prefer different themes, and never ship two puzzles that
 * are the same position with a different key move.
 */
const seenThemes = new Set();
const final = [];
for (const p of puzzles) {
  const tag = `${p.theme}|${p.moves}`;
  if (seenThemes.has(tag)) continue;
  seenThemes.add(tag);
  final.push(p);
}

const body =
  `/**\n` +
  ` * MKJ Chess — Tactical puzzles.\n` +
  ` *\n` +
  ` * Auto-generated by tools/make-puzzles.js. Each key move is a verified forced\n` +
  ` * mate produced by an independent brute-force search (src/mate-search.js), so\n` +
  ` * every entry is guaranteed legal and guaranteed to have a real solution.\n` +
  ` *\n` +
  ` * Regenerate after editing tools/make-puzzles.js:\n` +
  ` *   node tools/make-puzzles.js\n` +
  ` */\n` +
  `export const PUZZLES = ${JSON.stringify(final)};\n` +
  `export const PUZZLE_VERSION = 1;\n`;

writeFileSync(new URL('../src/puzzles.js', import.meta.url), body);

console.log(`Generated ${final.length} puzzles:`);
for (const p of final) {
  console.log(`  ${p.id.padEnd(14)} mate in ${p.moves}  ${p.theme.padEnd(15)} ${p.keyMoves.join(' ')}`);
}
if (rejected.length) {
  console.log(`\nRejected ${rejected.length} candidate(s):`);
  for (const r of rejected) console.log(`  ${r.id.padEnd(14)} ${r.reason}`);
}
